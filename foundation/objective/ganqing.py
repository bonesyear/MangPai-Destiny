# 二、条件化规则（条件 -> 行为）
# ════════════════════════════════════════════════════════════════

@dataclass
class GanQingRule:
    """一条干支性情规则：在 condition 满足时，得出 behavior。

    condition 字典可含键（全部可选，未列则该维度不约束；多键并存为 AND）：
      season          : str        单一季节（'春'/'夏'/'秋'/'冬'），子串匹配上下文季节
      season_any      : list[str]  多季节，命中其一即可（如 ['春','夏']）
      month_zhi       : list[str]  月令地支命中其一（如 ['丑','未']）
      sanhe           : str        三合局（如 '寅午戌'）：上下文 sanhe 相等，或三支俱在 branches
      tougian_any     : list[str]  透干：上下文 tougian 命中其一即可
      tougian_all     : list[str]  透干：须全部命中
      no_tougian      : list[str]  透干：这些均不透
      stems           : list[str]  柱中天干命中其一
      no_stems        : list[str]  柱中天干均无这些
      branches        : list[str]  柱中地支命中其一
      no_branches     : list[str]  柱中地支均无这些
      day_gz          : list[str]  日柱命中其一（如 ['乙未','乙丑']）
      state           : list[str]  旺衰/多寡态命中其一（如 ['火旺','水多','燥','湿']）
      branch_yang/yin : True       地支规则：branches 中含阳支/阴支
      branch_shengfang/siku/sibai : True  含生方/四库/四败
      general         : True       无条件（恒成立，常与说明性规则同用）
    """
    gan: str                       # 天干（地支规则为 ''，配 zhi_clause）
    fu_clause: str                 # 赋文原句
    condition: Dict[str, Any]      # 触发条件
    behavior: str                  # 行为/结论
    behavior_type: str             # 行为类型（见 BEHAVIOR_TYPES）
    rationale: str                 # 机理
    renshi: str                    # 任氏曰发挥（摘录）
    source: str = '赋'             # 出处：赋/原注/任氏发挥
    zhi_clause: str = ''           # 地支规则用的赋文键（如 'yang_yin'）


# 行为类型受控词汇
BEHAVIOR_TYPES = {
    '排斥', '宜坐', '喜', '忌', '克', '合', '化', '从',
    '势', '中性', '吉', '凶', '泄',
}


def _r(gan: str, fu_clause: str, condition: Dict[str, Any], behavior: str,
       behavior_type: str, rationale: str, renshi: str,
       source: str = '赋', zhi_clause: str = '') -> GanQingRule:
    """规则构造简写（同时校验 behavior_type 合法）。"""
    if behavior_type not in BEHAVIOR_TYPES:
        raise ValueError(f'未知 behavior_type={behavior_type!r} (gan={gan} clause={fu_clause})')
    return GanQingRule(gan=gan, fu_clause=fu_clause, condition=condition,
                       behavior=behavior, behavior_type=behavior_type,
                       rationale=rationale, renshi=renshi, source=source,
                       zhi_clause=zhi_clause)


