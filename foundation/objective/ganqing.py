def _norm_gan(gan: str) -> str:
    g = (gan or '').strip()
    return g[0] if g else ''


def _season_hit(rule_seasons: List[str], ctx_season: str) -> bool:
    """规则季节（列表）是否命中上下文季节。子串匹配：规则'春'可命中'春初'。"""
    if not ctx_season:
        return False
    return any(rs in ctx_season for rs in rule_seasons)


def _rule_matches(cond: Dict[str, Any], *, season: str, month_zhi: str,
                  sanhe: Optional[str], tougian: Set[str], stems: Set[str],
                  branches: Set[str], day_gz: str, states: Set[str]) -> bool:
    """逐键校验条件；全部满足才命中。"""
    # general：恒成立（但仍要满足其它并存键）
    # season / season_any
    if 'season' in cond and not _season_hit([cond['season']], season):
        return False
    if 'season_any' in cond and not _season_hit(list(cond['season_any']), season):
        return False
    # month_zhi
    if 'month_zhi' in cond and month_zhi not in cond['month_zhi']:
        return False
    # sanhe：上下文 sanhe 相等，或三支俱在 branches
    if 'sanhe' in cond:
        want = cond['sanhe']
        three = list(want)
        sanhe_ok = (sanhe == want) or all(b in branches for b in three)
        if not sanhe_ok:
            return False
    # tougian_any：命中其一即可
    if 'tougian_any' in cond and not any(t in tougian for t in cond['tougian_any']):
        return False
    # tougian_all：须全部命中
    if 'tougian_all' in cond and not all(t in tougian for t in cond['tougian_all']):
        return False
    # no_tougian：均不透
    if 'no_tougian' in cond and any(t in tougian for t in cond['no_tougian']):
        return False
    # stems：柱中天干命中其一
    if 'stems' in cond and not any(s in stems for s in cond['stems']):
        return False
    # no_stems
    if 'no_stems' in cond and any(s in stems for s in cond['no_stems']):
        return False
    # branches：柱中地支命中其一
    if 'branches' in cond and not any(b in branches for b in cond['branches']):
        return False
    # no_branches
    if 'no_branches' in cond and any(b in branches for b in cond['no_branches']):
        return False
    # day_gz
    if 'day_gz' in cond and day_gz not in cond['day_gz']:
        return False
    # state：旺衰/多寡态命中其一
    if 'state' in cond and not any(s in states for s in cond['state']):
        return False
    # 地支分类键（branch_yang/yin/shengfang/siku/sibai）：对单支判定，
    # 由 match_zhiqing 逐支调用前注入 branches=单支；此处按 branches 中是否存在该类支判定
    if 'branch_yang' in cond and not any(b in _YANG_ZHI for b in branches):
        return False
    if 'branch_yin' in cond and not any(b in _YIN_ZHI for b in branches):
        return False
    if 'branch_shengfang' in cond and not any(b in _SHENG_FANG for b in branches):
        return False
    if 'branch_siku' in cond and not any(b in _SI_KU for b in branches):
        return False
    if 'branch_sibai' in cond and not any(b in _SI_BAI for b in branches):
        return False
    return True


def match_ganqing(gan: str, *, season: Optional[str] = None, month_zhi: Optional[str] = None,
                  sanhe: Optional[str] = None, tougian: Optional[List[str]] = None,
                  stems: Optional[List[str]] = None, branches: Optional[List[str]] = None,
                  day_gz: Optional[str] = None, states: Optional[List[str]] = None) -> List[GanQingRule]:
    """按命局上下文匹配某天干的可用性情规则，返回命中规则列表（保持定义顺序）。

    season 可显式传更精细值（如 '春初'/'仲春'），否则由 month_zhi 推得泛季节。
    tougian 为透出天干列表；stems/branches 为柱中全部干/支；states 为旺衰多寡态集合。
    """
    g = _norm_gan(gan)
    if g not in GAN_QING_RULES:
        return []
    ctx_season = season or (season_of(month_zhi) if month_zhi else '')
    ctx = dict(season=ctx_season, month_zhi=month_zhi or '', sanhe=sanhe,
               tougian=set(tougian or []), stems=set(stems or []),
               branches=set(branches or []), day_gz=day_gz or '',
               states=set(states or []))
    return [r for r in GAN_QING_RULES[g] if _rule_matches(r.condition, **ctx)]


def match_zhiqing(zhi: str) -> List[GanQingRule]:
    """判定单个地支命中的地支性情规则（阳/阴支、生方/库/败）。

    对「败地逢冲仔细推」「生方怕动」等需冲合上下文的规则，此处只返回该支所属类别
    的规则（提示须结合冲合细推），是否真冲由上层 objective 冲合检测决定。
    """
    z = (zhi or '').strip()
    if not z:
        return []
    ctx = dict(season='', month_zhi='', sanhe=None, tougian=set(), stems=set(),
               branches={z}, day_gz='', states=set())
    return [r for r in _ZHI_RULES if _rule_matches(r.condition, **ctx)]


def get_ganqing(gan: str) -> Optional[Dict[str, Any]]:
    """取某天干完整记录：赋文/原注/任氏曰/规则列表。无此干返回 None。"""
    g = _norm_gan(gan)
    if g not in GAN_FU:
        return None
    return {
        'gan': g,
        'fu': GAN_FU[g],
        'yuanzhu': GAN_YUANZHU.get(g, ''),
        'renshi': GAN_RENSHI.get(g, ''),
        'rules': GAN_QING_RULES.get(g, []),
    }


