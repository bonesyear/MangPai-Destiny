# 阳支 / 阴支（命家以子寅辰午申戌为阳，丑卯巳未酉亥为阴）
_YANG_ZHI: Set[str] = {'子', '寅', '辰', '午', '申', '戌'}
_YIN_ZHI: Set[str] = {'丑', '卯', '巳', '未', '酉', '亥'}

# 生方 / 四库 / 四败（地支赋用）
_SHENG_FANG: Set[str] = {'寅', '申', '巳', '亥'}   # 四生
