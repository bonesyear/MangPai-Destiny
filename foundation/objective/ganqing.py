def season_of(month_zhi: str) -> str:
    """月令地支 -> 季节（春/夏/秋/冬）。空或非法返回 ''。"""
    return _MONTH_SEASON.get(month_zhi, '')


def is_yang_zhi(zhi: str) -> bool:
    """地支是否为阳支（子寅辰午申戌）。"""
    return zhi in _YANG_ZHI


