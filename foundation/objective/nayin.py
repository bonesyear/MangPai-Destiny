def get_nayin(gz_str: str) -> str:
    """获取六十甲子纳音名称（纯查表）。

    Args:
        gz_str: 干支字符串，如 '甲子'

    Returns:
        纳音名称，如 '海中金'；无效输入返回空字符串
    """
    return NAYIN_TABLE.get(gz_str, '')


def get_nayin_wuxing(gz_str: str) -> str:
    """获取干支纳音的五行归类（干支 -> 纳音名 -> 五行）。

    Args:
        gz_str: 干支字符串，如 '甲子'

    Returns:
        纳音五行，如 '金'；无效输入返回空字符串
    """
    return NAYIN_WUXING.get(get_nayin(gz_str), '')


