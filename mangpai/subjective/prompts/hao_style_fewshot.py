def format_fewshot_block(examples: list | None = None) -> str:
    """把 FEWSHOT_EXAMPLES 渲染成三段式文本块，拼进 LLM 的 user message。"""
    examples = examples if examples is not None else FEWSHOT_EXAMPLES
    parts = []
    for ex in examples:
        parts.append(
            f"【八字】{ex['bazi']}\n"
            f"【引擎结论】{ex['engine']}\n"
            f"【郝断语】{ex['hao']}"
        )
    return "\n\n".join(parts)
