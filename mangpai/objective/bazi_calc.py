#  自检：2026-01-01 → 2026-07-12 逐日追溯 = 丁亥
# ════════════════════════════════════════════════════════════════
def _self_check() -> None:
    """逐日追溯验证：2026-01-01 起，至 2026-07-12，确认日柱 = 丁亥。"""
    start = date(2026, 1, 1)
    end = date(2026, 7, 12)
    # 2026-01-01 日柱 = 乙亥（与流行公式 base0 / year_day_base 一致）
    assert day_gz(2026, 1, 1) == '乙亥', day_gz(2026, 1, 1)
    # 逐日 +1 推进至 2026-07-12
    cur = start
    last = day_gz_index(cur.year, cur.month, cur.day)
    while cur < end:
        cur = cur + timedelta(days=1)
        last = (last + 1) % 60
        assert day_gz_index(cur.year, cur.month, cur.day) == last
    # 终点应为丁亥（六十甲子序 23）
    final = day_gz(end.year, end.month, end.day)
    assert final == '丁亥', f'自检失败：2026-07-12 日柱 = {final}，期望 丁亥'
    # 流行公式（21 世纪形式）对 2026 应回退一致：year_day_base(2026)=11=乙亥
    assert year_day_base(2026) == 11
    assert year_day_base_formula(2026) == 11  # 21 世纪形式亦 = 11
    print(f'自检通过：2026-01-01 乙亥 → 逐日追溯 → 2026-07-12 {final} ✅')


