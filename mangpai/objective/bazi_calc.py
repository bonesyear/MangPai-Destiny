def calc_bazi_full(year: int, month: int, day: int, hour: int, minute: int,
                   gender: str, city_lon: float,
                   yin_method: str = 'same_as_yang',
                   shensha_reference: str = 'day',
                   late_zi_method: str = 'next_day') -> Dict[str, Any]:
    """完整八字排盘（盲派 engine 入口所需最小契约）。

    内部完成四柱（compute_four_pillars）+ 十神 + 空亡 + 地支关系 + 大运，
    返回 MangpaiEngine可直接消费的 bazi_data 字典。

    Args:
        year: 公历年
        month: 公历月
        day: 公历日
        hour: 时（0-23，北京时间）
        minute: 分（0-59）
        gender: '男' / '女'（亦接受 'male'/'female'）
        city_lon: 城市经度（东经，度），用于真太阳时校正
        yin_method: 阴干方向（盲派默认 'same_as_yang'，阴阳同生同死）；
            本字段保留以与 engine.calc_mangpai_full 签名对齐，盲派十二长生
            由 MangpaiEngine 自行计算（同生同死），本排盘不产出 chang_sheng。
            （F1 标注：死形参——接收不用；engine 侧透传亦无消费方，双层断路。
             删除须动公共签名，留签名清理批。）
        shensha_reference: 神煞参考柱（'day' 日支盲派（默认，F13 起）/
            'year' 年支传统）；保留以对齐签名，神煞由
            MangpaiEngine.compute_shensha_ext 自行计算。
            （死形参——本层接收不用；engine 层该参有效，默认 'day'。）
        late_zi_method: 晚子时日柱处理（'next_day' 子初换日 / 'same_day'
            子正换日·书例口径），透传 compute_four_pillars（F3 批暴露，
            批9 P0-3）。

    Returns:
        bazi_data：包含 input/bazi/shishen/kong_wang/di_zhi_relations/da_yun
        等键；MangpaiEngine 读取这些键进行盲派分析（nayin/canggan/wuxing/
        chang_sheng 等由 engine 自行重算，故此处不产出，避免重复）。
    """
    fp = compute_four_pillars(year, month, day, hour, minute, city_lon,
                              late_zi_method=late_zi_method)
    pillars = {k: fp[k] for k in ('year_gz', 'month_gz', 'day_gz', 'hour_gz')}
    day_gz = pillars['day_gz']
    day_gan = day_gz[0]
    day_zhi = day_gz[1]

    shishen = compute_shishen(
        day_gan,
        pillars['year_gz'], pillars['month_gz'],
        pillars['day_gz'], pillars['hour_gz'],
    )
    kong_wang = get_kong_wang(day_gan, day_zhi)
    zhis = [pillars[k][1] for k in ('year_gz', 'month_gz', 'day_gz', 'hour_gz')]
    rels = get_di_zhi_relations(zhis)
    da_yun = compute_da_yun(year, month, day, hour, minute, gender, fp)

    return {
        'input': {
            'year': year, 'month': month, 'day': day,
            'hour': hour, 'minute': minute,
            'gender': gender, 'city_lon': city_lon,
        },
        'bazi': {
            'year': pillars['year_gz'],
            'month': pillars['month_gz'],
            'day': pillars['day_gz'],
            'hour': pillars['hour_gz'],
            'full': (f"{pillars['year_gz']} {pillars['month_gz']} "
                     f"{pillars['day_gz']} {pillars['hour_gz']}"),
        },
        'shishen': shishen,
        'kong_wang': kong_wang,
        'di_zhi_relations': rels,
        'da_yun': da_yun,
    }


