#  大运（月柱起，阳男阴女顺行；起运岁 = 整日差/3 余一舍余二进一，虚岁）
# ════════════════════════════════════════════════════════════════
# （F1 批删除：_JIE_QI_NAMES/_JIE_NAME_TO_ORDERIDX 两表全库 0 引用=死数据；
#  jiaoyun.py 自有一套节气索引表，不受影响。）


def compute_da_yun(year: int, month: int, day: int, hour: int, minute: int,
                   gender: str, four_pillars: Dict[str, str]) -> Dict[str, Any]:
    """计算大运（起运岁数 + 方向 + 8 步序列）。

    - 阳男阴女→顺排，阴男阳女→逆排
    - 起运岁数：书口径（理象学:3846-3877）——出生日到最近节的整日差 ÷ 3，
      余一舍余二进一，不足一天按一岁，结果为整数虚岁
    - 大运序列从月柱起，顺排 +1、逆排 −1，每步 10 年
    """
    y_gz = four_pillars['year_gz']
    m_gz = four_pillars['month_gz']
    is_yang = y_gz[0] in _YANG_GAN
    is_male = gender in ('男', 'male')
    forward = (is_yang and is_male) or (not is_yang and not is_male)
    direction = '顺' if forward else '逆'

    birth = datetime(year, month, day, hour, minute)
    if forward:
        pos = bisect.bisect_right(_JIE_DTS, birth)
        if pos >= len(_JIE_TIMELINE):
            pos = len(_JIE_TIMELINE) - 1
    else:
        pos = bisect.bisect_right(_JIE_DTS, birth) - 1
        if pos < 0:
            pos = 0
    jie_dt, _jbranch, jie_name = _JIE_TIMELINE[pos]
    # 起运岁书口径（理象学:3846-3877）：
    #   - 天数 = 生日到最近节的整日差（非精确时刻天数；书例 2005-3-15 逆数
    #     至惊蛰 3-5 差 10 天，:3916-3918）
    #   - 用三除之，除不尽时余一舍掉、余二进一（:3854-3856）
    #   - 不足一天也以一岁起运排；最大十最小一（:3864-3873）
    #   - 所得为整数虚岁（「所算出的起运岁数是以虚岁定」:3875-3877）
    days = abs((jie_dt.date() - birth.date()).days)
    q, r = divmod(days, 3)
    start_age = q + (1 if r == 2 else 0)
    if start_age < 1:
        start_age = 1

    start_age_str = f'{start_age}岁（虚岁）'

    mt = GAN.index(m_gz[0])
    md = ZHI.index(m_gz[1])
    step = 1 if forward else -1
    dayun: List[Dict[str, Any]] = []
    for i in range(8):
        tg = (mt + step * (i + 1)) % 10
        dz = (md + step * (i + 1)) % 12
        age = start_age + i * 10
        dayun.append({'gz': GAN[tg] + ZHI[dz], 'start_age': age, 'end_age': age + 10})

    # F1 标注：direction/forward/start_age_str/jie_name/days 五键 engine 不读
    # （engine 只取 dayun 列表与 start_age，批9 审计）=死字段，保留输出契约不删。
    return {
        'direction': direction,
        'forward': forward,
        'start_age': start_age,
        'start_age_str': start_age_str,
        'jie_name': jie_name,
        'days': days,
        'dayun': dayun,
    }


# ════════════════════════════════════════════════════════════════
#  公共接口：calc_bazi_full
