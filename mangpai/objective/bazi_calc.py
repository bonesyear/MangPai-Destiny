# ── 节气时刻索引（一次性构建，供月柱/年柱/大运查询）──────────────
def _build_jie_timeline() -> List[Tuple[datetime, int, str]]:
    """构建全量「节」时间线：(北京时间, 月支序, 节名)，按时刻升序。"""
    tl: List[Tuple[datetime, int, str]] = []
    for Y in range(SOLAR_TERM_YEAR_MIN, SOLAR_TERM_YEAR_MAX + 1):
        packed = SOLAR_TERMS[Y]
        for pos in _JIE_POS:
            m, d, h, mi = _unpack(packed[pos])
            branch = (pos // 2 + 2) % 12
            tl.append((datetime(Y, m, d, h, mi), branch, SOLAR_TERM_ORDER[pos]))
    tl.sort(key=lambda x: x[0])
    return tl


_JIE_TIMELINE: List[Tuple[datetime, int, str]] = _build_jie_timeline()
_JIE_DTS: List[datetime] = [x[0] for x in _JIE_TIMELINE]


def _lichun_dt(year: int) -> datetime:
    """该公历年立春时刻（北京时间）。年初出生者用以判年柱分界。"""
    m, d, h, mi = _unpack(SOLAR_TERMS[year][0])  # 立春 = 规范序 0
    return datetime(year, m, d, h, mi)


